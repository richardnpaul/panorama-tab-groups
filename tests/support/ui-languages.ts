/**
 * The folder a browser set to the language takes: the one named like the language (`pt-BR` is
 * `pt_BR`), else the one named like the language alone (`pt`); none when there is neither, and
 * then English is shown. Firefox takes one more step, found by asking it (`firefox-locale-folders.spec.ts`):
 * a folder of another region of the language (`es_419` for `es-MX`, `de_CH` for `de`), which Chromium
 * does not (`chromium-locale-folders.spec.ts`).
 */
export function folderFor(
  language: string,
  folders: readonly string[],
  anyRegion = false,
): string | undefined {
  const named = language.replace('-', '_');
  const alone = named.split('_')[0] ?? named;
  return [
    named,
    alone,
    ...(anyRegion
      ? folders.filter((folder) => folder.split('_')[0] === alone)
      : []),
  ].find((folder) => folders.includes(folder));
}

/** The folders that some language takes, from those that were given, in the order given */
export function reachableFolders(
  languages: readonly string[],
  folders: readonly string[],
  anyRegion = false,
): string[] {
  const taken = new Set(
    languages.map((language) => folderFor(language, folders, anyRegion)),
  );
  return folders.filter((folder) => taken.has(folder));
}
